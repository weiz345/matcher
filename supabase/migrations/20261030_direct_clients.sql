-- Direct clients: Supabase Auth + private Storage + access-controlled RPCs.
-- Legacy hinge schema is intentionally untouched.
begin;
create schema if not exists dating;
revoke all on schema dating from public, anon;
grant usage on schema dating to authenticated;

create table if not exists dating.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 name text not null check(length(trim(name)) between 1 and 40),
 age integer not null check(age between 18 and 120),
 location text not null default 'Brooklyn' check(length(location) between 1 and 80),
 job text not null default '' check(length(job)<=80),height text not null default '' check(length(height)<=30),
 created_at timestamptz not null default now());
create table if not exists dating.prompts (
 id uuid primary key default gen_random_uuid(),user_id uuid not null references dating.profiles(id) on delete cascade,
 title text not null check(length(trim(title)) between 1 and 100),answer text not null check(length(trim(answer)) between 1 and 300),position integer not null);
create table if not exists dating.photos (
 id uuid primary key,user_id uuid not null references dating.profiles(id) on delete cascade,
 path text not null unique,mime text not null,position integer not null);
create table if not exists dating.likes (
 sender uuid not null references dating.profiles(id) on delete cascade,
 recipient uuid not null references dating.profiles(id) on delete cascade,
 item_type text not null check(item_type in ('photo','prompt')),item_id uuid not null,
 comment text not null default '' check(length(comment)<=300),created_at timestamptz not null default now(),
 primary key(sender,recipient),check(sender<>recipient));
create table if not exists dating.conversations (
 id uuid primary key default gen_random_uuid(),a uuid not null references dating.profiles(id),b uuid not null references dating.profiles(id),
 active boolean not null default true,created_at timestamptz not null default now(),unique(a,b),check(a<b));
create table if not exists dating.messages (
 id bigint generated by default as identity primary key,conversation_id uuid not null references dating.conversations(id),
 sender uuid not null references dating.profiles(id),text text not null check(length(trim(text)) between 1 and 1000),
 client_id text not null check(length(client_id) between 1 and 100),created_at timestamptz not null default now(),unique(conversation_id,sender,client_id));
create table if not exists dating.blocks (
 blocker uuid not null references dating.profiles(id),blocked uuid not null references dating.profiles(id),primary key(blocker,blocked),check(blocker<>blocked));
create table if not exists dating.passes (
 user_id uuid not null references dating.profiles(id),target uuid not null references dating.profiles(id),primary key(user_id,target));
create index if not exists dating_messages_history on dating.messages(conversation_id,id);
create index if not exists dating_likes_recipient on dating.likes(recipient);

create or replace function dating.allowed(other uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and auth.uid()<>other and not exists(
 select 1 from dating.blocks where (blocker=auth.uid() and blocked=other) or (blocked=auth.uid() and blocker=other));
$$;
create or replace function dating.active_chat(cid uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select exists(select 1 from dating.conversations c where c.id=cid and c.active
 and auth.uid() in(c.a,c.b) and dating.allowed(case when c.a=auth.uid() then c.b else c.a end));
$$;

alter table dating.profiles enable row level security;
alter table dating.prompts enable row level security;
alter table dating.photos enable row level security;
alter table dating.likes enable row level security;
alter table dating.conversations enable row level security;
alter table dating.messages enable row level security;
alter table dating.blocks enable row level security;
alter table dating.passes enable row level security;
-- Mutations are only through checked functions, not direct table writes.
revoke all on all tables in schema dating from public,anon,authenticated;
grant select on all tables in schema dating to authenticated;
drop policy if exists profile_read on dating.profiles;
create policy profile_read on dating.profiles for select to authenticated using(id=auth.uid() or dating.allowed(id));
drop policy if exists prompt_read on dating.prompts;
create policy prompt_read on dating.prompts for select to authenticated using(user_id=auth.uid() or dating.allowed(user_id));
drop policy if exists photo_read on dating.photos;
create policy photo_read on dating.photos for select to authenticated using(user_id=auth.uid() or dating.allowed(user_id));
drop policy if exists like_read on dating.likes;
create policy like_read on dating.likes for select to authenticated using(auth.uid() in(sender,recipient) and dating.allowed(case when sender=auth.uid() then recipient else sender end));
drop policy if exists chat_read on dating.conversations;
create policy chat_read on dating.conversations for select to authenticated using(dating.active_chat(id));
drop policy if exists message_read on dating.messages;
create policy message_read on dating.messages for select to authenticated using(dating.active_chat(conversation_id));
drop policy if exists block_read on dating.blocks;
create policy block_read on dating.blocks for select to authenticated using(blocker=auth.uid());
drop policy if exists pass_read on dating.passes;
create policy pass_read on dating.passes for select to authenticated using(user_id=auth.uid());

create or replace function dating.new_user() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 insert into dating.profiles(id,name,age) values(new.id,
 left(coalesce(nullif(trim(new.raw_user_meta_data->>'name'),''),'New member'),40),
 coalesce((new.raw_user_meta_data->>'age')::integer,18));
 insert into dating.prompts(user_id,title,answer,position) values(new.id,'My simple pleasures','Good coffee and great conversation.',0);
 return new;
end;$$;
drop trigger if exists dating_new_user on auth.users;
create trigger dating_new_user after insert on auth.users for each row execute function dating.new_user();

create or replace function dating.person(uid uuid) returns jsonb
language sql stable security definer set search_path='' as $$
 select jsonb_build_object('id',p.id,'name',p.name,'age',p.age,'location',p.location,'job',p.job,'height',p.height,
 'photos',coalesce((select jsonb_agg('/api/photos/'||id::text order by position,id) from dating.photos where user_id=p.id),'[]'::jsonb),
 'prompts',coalesce((select jsonb_agg(jsonb_build_object('id',id,'title',title,'answer',answer) order by position,id) from dating.prompts where user_id=p.id),'[]'::jsonb))
 from dating.profiles p where p.id=uid;
$$;
create or replace function public.dating_messages(p_conversation uuid,p_before bigint default 9223372036854775807) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 if not dating.active_chat(p_conversation) then raise exception 'Conversation unavailable' using errcode='42501'; end if;
 return jsonb_build_object('messages',coalesce((select jsonb_agg(jsonb_build_object('id',m.id::text,'text',m.text,'mine',m.sender=auth.uid(),'senderID',m.sender,'createdAt',floor(extract(epoch from m.created_at))::bigint) order by m.id)
 from (select * from dating.messages where conversation_id=p_conversation and id<p_before order by id desc limit 100)m),'[]'::jsonb));
end;$$;
create or replace function public.dating_bootstrap() returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare me uuid:=auth.uid();begin
 if me is null or not exists(select 1 from dating.profiles where id=me) then raise exception 'Please sign in' using errcode='42501';end if;
 return jsonb_build_object('me',dating.person(me),
 'discover',coalesce((select jsonb_agg(dating.person(p.id) order by p.created_at,p.id) from(
 select * from dating.profiles x where dating.allowed(x.id)
 and not exists(select 1 from dating.passes where user_id=me and target=x.id)
 and not exists(select 1 from dating.likes where sender=me and recipient=x.id)
 and not exists(select 1 from dating.conversations where (a=me and b=x.id) or (b=me and a=x.id))
 order by x.created_at,x.id limit 100)p),'[]'::jsonb),
 'likes',coalesce((select jsonb_agg(jsonb_build_object('id',l.sender,'person',dating.person(l.sender),'comment',l.comment,'itemType',l.item_type,'itemID',l.item_id) order by l.created_at desc)
 from (select * from dating.likes x where recipient=me and dating.allowed(sender)
 and not exists(select 1 from dating.passes where user_id=me and target=x.sender)
 and not exists(select 1 from dating.conversations where (a=me and b=x.sender) or (b=me and a=x.sender))
 order by created_at desc limit 100)l),'[]'::jsonb),
 'matches',coalesce((select jsonb_agg(jsonb_build_object('id',c.id,'person',dating.person(case when c.a=me then c.b else c.a end),'messages',public.dating_messages(c.id)->'messages') order by c.created_at desc)
 from(select * from dating.conversations where dating.active_chat(id) order by created_at desc limit 100)c),'[]'::jsonb));
end;$$;

create or replace function public.dating_photo(p_id uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare result jsonb;begin
 select jsonb_build_object('path',path,'mime',mime) into result from dating.photos where id=p_id and (user_id=auth.uid() or dating.allowed(user_id));
 if result is null then raise exception 'Photo unavailable' using errcode='42501';end if;return result;
end;$$;

create or replace function dating.like_person(target uuid,kind text,item uuid,comment_text text) returns uuid
language plpgsql security definer set search_path='' as $$
declare me uuid:=auth.uid();lo uuid:=least(auth.uid(),target);hi uuid:=greatest(auth.uid(),target);cid uuid;enabled boolean;
begin
 if not dating.allowed(target) or not exists(select 1 from dating.profiles where id=target) then raise exception 'Profile unavailable';end if;
 select id,active into cid,enabled from dating.conversations where a=lo and b=hi;
 if cid is not null then
 if not enabled then raise exception 'This connection has ended';end if;return cid;end if;
 if not ((kind='photo' and exists(select 1 from dating.photos where id=item and user_id=target))
 or (kind='prompt' and exists(select 1 from dating.prompts where id=item and user_id=target))) then raise exception 'Like must reference this person''s photo or prompt';end if;
 insert into dating.likes(sender,recipient,item_type,item_id,comment) values(me,target,kind,item,comment_text) on conflict do nothing;
 delete from dating.passes where user_id=me and dating.passes.target=like_person.target;
 if exists(select 1 from dating.likes where sender=target and recipient=me) then
 insert into dating.conversations(a,b)values(lo,hi)on conflict(a,b)do update set a=excluded.a returning id into cid;end if;
 return cid;
end;$$;

create or replace function public.dating_action(p_action text,p_body jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare me uuid:=auth.uid();target uuid;cid uuid;match_id uuid;pid uuid;item jsonb;idx integer:=0;owned uuid[];kept uuid[]:='{}';pathname text;
begin
 if me is null or not exists(select 1 from dating.profiles where id=me) then raise exception 'Please sign in' using errcode='42501';end if;
 -- Serialize writes for this small MVP, including reciprocal-like races.
 perform pg_advisory_xact_lock(723194043);
 if p_action in('like','accept','pass','block') then
 target:=(p_body->>'target')::uuid;
 if not dating.allowed(target) or not exists(select 1 from dating.profiles where id=target) then raise exception 'Profile unavailable';end if;end if;
 if p_action='like' then
 match_id:=dating.like_person(target,p_body->>'itemType',(p_body->>'itemID')::uuid,coalesce(p_body->>'comment',''));
 elsif p_action='accept' then
 if not exists(select 1 from dating.likes where sender=target and recipient=me) then raise exception 'Like unavailable';end if;
 select id into pid from dating.photos where user_id=target order by position,id limit 1;
 if pid is not null then match_id:=dating.like_person(target,'photo',pid,'');
 else select id into pid from dating.prompts where user_id=target order by position,id limit 1;
 match_id:=dating.like_person(target,'prompt',pid,'');end if;
 elsif p_action='pass' then insert into dating.passes values(me,target)on conflict do nothing;
 elsif p_action='revisit' then delete from dating.passes where user_id=me;
 elsif p_action='block' then
 insert into dating.blocks values(me,target)on conflict do nothing;
 update dating.conversations set active=false where (a=me and b=target)or(a=target and b=me);
 delete from dating.likes where(sender=me and recipient=target)or(sender=target and recipient=me);
 elsif p_action in('message','unmatch') then
 cid:=(p_body->>'conversation')::uuid;
 if not dating.active_chat(cid) then raise exception 'Conversation unavailable' using errcode='42501';end if;
 if p_action='unmatch' then update dating.conversations set active=false where id=cid;
 else insert into dating.messages(conversation_id,sender,text,client_id) values(cid,me,trim(p_body->>'text'),p_body->>'clientID')on conflict do nothing;end if;
 elsif p_action='profile' then
 if jsonb_typeof(p_body->'prompts')<>'array' or jsonb_array_length(p_body->'prompts')not between 1 and 3 then raise exception 'Provide 1–3 prompts';end if;
 update dating.profiles set name=trim(p_body->>'name'),age=(p_body->>'age')::integer,location=trim(p_body->>'location'),job=coalesce(p_body->>'job',''),height=coalesce(p_body->>'height','')where id=me;
 select array_agg(id) into owned from dating.prompts where user_id=me;
 for item in select * from jsonb_array_elements(p_body->'prompts')loop
 pid:=coalesce((item->>'id')::uuid,gen_random_uuid());
 if not(pid=any(coalesce(owned,'{}')))then pid:=gen_random_uuid();end if;
 if pid=any(kept)then raise exception 'Duplicate prompt';end if;kept:=array_append(kept,pid);
 insert into dating.prompts(id,user_id,title,answer,position)values(pid,me,trim(item->>'title'),trim(item->>'answer'),idx)
 on conflict(id)do update set title=excluded.title,answer=excluded.answer,position=excluded.position;idx:=idx+1;end loop;
 delete from dating.prompts where user_id=me and not(id=any(kept));
 elsif p_action='photo_register' then
 pid:=(p_body->>'id')::uuid;pathname:=me::text||'/'||pid::text;
 if (select count(*)from dating.photos where user_id=me)>=6 then raise exception 'Maximum 6 photos';end if;
 if not exists(select 1 from storage.objects where bucket_id='dating-photos' and name=pathname)then raise exception 'Upload photo first';end if;
 insert into dating.photos(id,user_id,path,mime,position)values(pid,me,pathname,coalesce(p_body->>'mime','image/jpeg'),(select count(*)from dating.photos where user_id=me));
 elsif p_action='photo_delete' then
 delete from dating.photos where id=(p_body->>'id')::uuid and user_id=me;
 if not found then raise exception 'Photo unavailable' using errcode='42501';end if;
 else raise exception 'Unknown action';end if;
 return jsonb_build_object('app',public.dating_bootstrap(),'matchID',match_id);
end;$$;

